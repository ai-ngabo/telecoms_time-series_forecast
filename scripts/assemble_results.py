"""
assemble_results.py
________________
 Collects outputs for Section 4 of the brief from per-model, per-area
 JSON results and prediction .npz files (generated by sarima.py, gru.py,
 lightgbm.py). Produces:
   - Metrics tables per area (tables/metrics_<area>.csv)
   - Timing table (tables/timing_table.csv)
   - Actual-vs-predicted plots grid (figures/fig5_actual_vs_predicted_grid.png)
   - Failure-case analysis (tables/failure_case_analysis.csv)

CLI Usage:
    python scripts/assemble_results.py processed_data
"""
import sys
import os
import json
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

PROJECT_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TABLES_DIR = os.path.join(PROJECT_ROOT, "tables")
FIG_DIR = os.path.join(PROJECT_ROOT, "figures")

MODELS = ["sarima", "gru", "lightgbm"]
MODEL_LABELS = {"sarima": "SARIMA", "gru": "GRU", "lightgbm": "LightGBM"}
AREAS = ["5161", "5059", "5259"]

FAILURE_START = "2013-12-20"  # Friday
FAILURE_END = "2013-12-22"    # Sunday (weekend inside the test week)


def load_result(model, area):
    path = os.path.join(TABLES_DIR, f"{model}_{area}_result.json")
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def load_preds(data_dir, model, area):
    path = os.path.join(data_dir, f"{model}_preds_{area}.npz")
    npz = np.load(path)
    return npz["y_true"], npz["y_pred"], pd.to_datetime(npz["test_index"])


def build_metric_tables():
    for area in AREAS:
        rows = {}
        for model in MODELS:
            result = load_result(model, area)
            rows[MODEL_LABELS[model]] = result["metrics"]
        table = pd.DataFrame(rows).T
        table.index.name = "Model"
        out_path = os.path.join(TABLES_DIR, f"metrics_{area}.csv")
        table.to_csv(out_path)
        print(f"\n=== Metrics table - Square {area} ===")
        print(table.round(2))


def build_timing_table(data_dir):
    records = []
    for model in MODELS:
        train_times, infer_times = [], []
        for area in AREAS:
            result = load_result(model, area)
            train_times.append(result["train_timing"]["mean_seconds"])
            infer_times.append(result["inference_timing"]["mean_seconds"])
        records.append({
            "Model": MODEL_LABELS[model],
            "Avg train time (s, across 3 areas)": np.mean(train_times),
            "Avg inference time (s, full test set, across 3 areas)": np.mean(infer_times),
        })
    table = pd.DataFrame(records).set_index("Model")
    out_path = os.path.join(TABLES_DIR, "timing_table.csv")
    table.to_csv(out_path)
    print("\n=== Timing table (averaged across 3 areas) ===")
    print(table.round(3))
    return table


def build_prediction_grid(data_dir):
    fig, axes = plt.subplots(3, 3, figsize=(18, 10), sharex=True)
    for row, area in enumerate(AREAS):
        for col, model in enumerate(MODELS):
            y_true, y_pred, test_index = load_preds(data_dir, model, area)
            ax = axes[row, col]
            ax.plot(test_index, y_true, label="Actual", color="black", linewidth=0.8)
            ax.plot(test_index, y_pred, label="Predicted", color="crimson",
                     linewidth=0.8, alpha=0.8)
            ax.set_title(f"Square {area} - {MODEL_LABELS[model]}", fontsize=10)
            if row == 0 and col == 0:
                ax.legend(fontsize=8)
            if col == 0:
                ax.set_ylabel("Internet traffic")
            ax.tick_params(axis="x", rotation=30)
    fig.suptitle("Figure 5: Actual vs Predicted - Test week (Dec 16-22, 2013)", y=1.02)
    fig.tight_layout()
    out_path = os.path.join(FIG_DIR, "fig5_actual_vs_predicted_grid.png")
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"\n[fig5] saved to {out_path}")


def failure_case_analysis(data_dir):
    records = []
    for area in AREAS:
        for model in MODELS:
            y_true, y_pred, test_index = load_preds(data_dir, model, area)
            df = pd.DataFrame({"y_true": y_true, "y_pred": y_pred}, index=test_index)

            failure_mask = (df.index >= FAILURE_START) & (df.index < pd.Timestamp(FAILURE_END) + pd.Timedelta(days=1))
            rest = df[~failure_mask]
            failure = df[failure_mask]

            def rmse(sub):
                return float(np.sqrt(np.mean((sub["y_true"] - sub["y_pred"]) ** 2)))

            records.append({
                "Area": area, "Model": MODEL_LABELS[model],
                "RMSE (weekdays, Dec 16-19)": rmse(rest),
                "RMSE (weekend, Dec 20-22)": rmse(failure),
                "Degradation (%)": (rmse(failure) - rmse(rest)) / rmse(rest) * 100,
            })
    table = pd.DataFrame(records)
    out_path = os.path.join(TABLES_DIR, "failure_case_analysis.csv")
    table.to_csv(out_path, index=False)
    print("\n=== Failure-case analysis: weekend (Dec 20-22) vs weekdays ===")
    print(table.round(2).to_string(index=False))
    return table


def main(data_dir):
    build_metric_tables()
    build_timing_table(data_dir)
    build_prediction_grid(data_dir)
    failure_case_analysis(data_dir)


if __name__ == "__main__":
    main(sys.argv[1])